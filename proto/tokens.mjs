export function tokensCss(d) {
  const light = palette(d.colors, d.light);
  const dark = palette(d.colors, d.dark);
  const decl = (obj, pfx = '') =>
    Object.entries(obj)
      .map(([k, v]) => `  --${pfx}${k}: ${v};`)
      .join('\n');
  const color = (p) =>
    Object.entries(p)
      .map(([k, v]) => `  --color-${k}: ${v};`)
      .join('\n');
  return `/* Generated by proto/tokens.mjs. Do not edit by hand. */
:root {
${decl(typeScale(d.type))}
${decl(spaceScale(d.space))}
  --measure: 34em;
  --measure-wide: 64rem;
  --radius-s: 0.25rem;
  --line-thin: 1px;
  --line-path: 3px;
  --leading-tight: 1.15;
  --leading-body: 1.6;
  color-scheme: light dark;
${color(light)}
}
/* Screen only: print always uses the light palette. */
@media screen and (prefers-color-scheme: dark) {
  :root {
${color(dark).replace(/^/gm, '  ')}
  }
}
`;
}
